// Accents for the bindings: the eight named colors a node's `data.color` may name, read from the design system's
// color rule (design-system/geometry/color.ts → TOPIC_ORDER, synced from the Visualli design system) so the Python and
// TypeScript bindings never restate them. Run by `make generate` after the models are generated.
//
//   node scripts/gen-bindings-accents.mjs           writes bindings/typescript/src/accents.ts and the accents block
//                                                   at the end of bindings/python/visualli.py
//
// A name drawn in the reader's palette and theme is an accent; any other color (e.g. a hex) is drawn as given.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const colorTs = readFileSync(join(root, 'design-system/geometry/color.ts'), 'utf8');
const m = /export const TOPIC_ORDER = \[([^\]]*)\] as const;/.exec(colorTs);
if (!m) { console.error('gen-bindings-accents: TOPIC_ORDER not found in design-system/geometry/color.ts'); process.exit(1); }
const accents = [...m[1].matchAll(/'([a-z]+)'/g)].map((x) => x[1]);
if (accents.length < 2) { console.error('gen-bindings-accents: no accents read from TOPIC_ORDER'); process.exit(1); }

const SOURCE = 'design-system/geometry/color.ts';
const quoted = accents.map((a) => `"${a}"`).join(', ');

// ── TypeScript ──────────────────────────────────────────────────────────────
writeFileSync(join(root, 'bindings/typescript/src/accents.ts'), `// Generated by scripts/gen-bindings-accents.mjs from ${SOURCE} - don't edit.
//
// A node's \`data.color\` may name one of these accents (any case, surrounding spaces ignored): every renderer draws it
// in the reader's palette and theme. Any other color (e.g. "#b7e7f3") is drawn exactly as given, in every palette.

/** The ${accents.length} accents, in the order renderers give them to ideas without a color (by position among siblings). */
export const ACCENTS = [${accents.map((a) => `'${a}'`).join(', ')}] as const;
export type Accent = (typeof ACCENTS)[number];

/** The accent a node color names, or null (no color, or a custom color such as a hex). */
export function accentOf(color: string | null | undefined): Accent | null {
  if (!color) return null;
  const c = color.trim().toLowerCase();
  return (ACCENTS as readonly string[]).includes(c) ? (c as Accent) : null;
}
`);

// ── Python (appended to the generated models, so `from visualli import ACCENTS`) ────────────────────────────────
const pyPath = join(root, 'bindings/python/visualli.py');
const MARK = '# ── Accents ';
let py = readFileSync(pyPath, 'utf8');
const at = py.indexOf(MARK);
if (at >= 0) py = py.slice(0, at);
py = py.replace(/\s*$/, '\n') + `

${MARK}${'─'.repeat(80 - MARK.length)}
# Generated by scripts/gen-bindings-accents.mjs from ${SOURCE} - don't edit.
#
# A node's \`data.color\` may name one of these accents (any case, surrounding spaces ignored): every renderer draws it
# in the reader's palette and theme. Any other color (e.g. "#b7e7f3") is drawn exactly as given, in every palette.

Accent = Literal[${quoted}]

#: The ${accents.length} accents, in the order renderers give them to ideas without a color (by position among siblings).
ACCENTS: tuple[Accent, ...] = (${quoted})


def accent_of(color: str | None) -> Accent | None:
    """The accent a node color names, or None (no color, or a custom color such as a hex)."""
    if not color:
        return None
    c = color.strip().lower()
    return c if c in ACCENTS else None  # type: ignore[return-value]
`;
writeFileSync(pyPath, py);
console.log(`gen-bindings-accents: ${accents.join(', ')} → bindings/typescript/src/accents.ts, bindings/python/visualli.py`);
